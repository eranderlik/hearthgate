#!/usr/bin/env python3
"""Regenerates THIRD_PARTY_NOTICES.md from the helper's vendored Go modules
(run after a build, which creates helper/vendor) plus the bundled Java
libraries and the Go standard library."""
import os, re, sys, pathlib

root = pathlib.Path(__file__).resolve().parent.parent
vendor = root / "helper" / "vendor"
goroot = os.popen("go env GOROOT").read().strip()
if not (vendor / "modules.txt").exists():
    sys.exit("helper/vendor missing; run ./gradlew :core:buildHelperWasm first")

def detect(text):
    t = text.lower()
    if "apache license" in t and "version 2.0" in t: return "Apache-2.0"
    if "mozilla public license" in t: return "MPL-2.0"
    if "redistribution and use in source and binary forms" in t:
        return "BSD-3-Clause" if "neither the name" in t or "contributors may be used" in t else "BSD-2-Clause"
    if "permission is hereby granted, free of charge" in t: return "MIT"
    if "permission to use, copy, modify, and/or distribute" in t: return "ISC"
    return "see text"

mods = []
for line in (vendor / "modules.txt").read_text().splitlines():
    m = re.match(r"# (\S+) (\S+)", line)
    if m: mods.append((m.group(1), m.group(2)))

out = ["# Third-party notices", "",
       "The Tailcat for Minecraft jar bundles the following software. The networking",
       "helper is compiled from Go (including the modules below and the Go standard",
       "library) to WebAssembly and then to JVM bytecode; the Chicory WebAssembly",
       "runtime is bundled as a library. The optional native helper add-ons for",
       "dedicated servers contain the same Go code compiled as a native library.", "",
       "Generated by tools/third_party_notices.py.", "", "## Summary", "",
       "| Component | Version | License |", "|---|---|---|"]
texts = []
def add(name, version, lic_path):
    text = lic_path.read_text(errors="replace") if lic_path else ""
    out.append(f"| {name} | {version} | {detect(text) if text else 'unknown'} |")
    if text: texts.append((name, text))

add("Go standard library and runtime", os.popen("go env GOVERSION").read().strip(), pathlib.Path(goroot) / "LICENSE")
for path, ver in mods:
    d = vendor / path
    lic = None
    p = d
    while p != vendor.parent and lic is None:
        for n in ("LICENSE", "LICENSE.md", "LICENSE.txt", "COPYING", "LICENCE"):
            if (p / n).exists(): lic = p / n; break
        p = p.parent
    if d.exists():
        add(path, ver, lic)
out.append("| Chicory (com.dylibso.chicory: runtime, wasm, build-time compiler output) | 1.7.5 | Apache-2.0 |")
out.append("| tailcat-for-minecraft demo (portions of the invitation format and UI flow) | 2026-08 | BSD-3-Clause |")
out += ["", "## License texts", ""]
for name, text in texts:
    out += [f"### {name}", "", "```", text.strip(), "```", ""]
(root / "THIRD_PARTY_NOTICES.md").write_text("\n".join(out) + "\n")
print(f"wrote notices for {len(texts)} components")
